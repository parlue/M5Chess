"""Generate the Core2 RGB565 tiles from the repository's WebP source images."""
from pathlib import Path
import argparse
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
MAIN=ROOT/'esp32_core2/main'

def pieces():
    lines=['#pragma once','#include <cstdint>',
           '// Merida pieces from eChessTactics; see PIECES-LICENSE.txt.',
           'static const uint16_t PieceTiles[12][2][625] = {']
    for piece in 'KQRBNPkqrbnp':
        name=('w' if piece.isupper() else 'b')+piece.upper()+'.webp'
        im=Image.open(ROOT/'assets/merida'/name).convert('RGBA')
        im=im.crop(im.getbbox())
        im.thumbnail((23,23),Image.Resampling.LANCZOS)
        im.putdata([(255 if r>145 else 20,)*3+(255 if a>=128 else 0,)
                    for r,g,b,a in im.getdata()])
        lines.append('{')
        for rgb in [(235,242,250),(120,161,204)]:
            canvas=Image.new('RGBA',(25,25),rgb+(255,))
            canvas.alpha_composite(im,((25-im.width)//2,(25-im.height)//2))
            data=[((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b,a in canvas.getdata()]
            lines.append('{'+','.join(f'0x{x:04x}' for x in data)+'},')
        lines.append('},')
    lines.append('};')
    return '\n'.join(lines)

def queens():
    lines=['#pragma once','#include <cstdint>',
           '// BeatVirgin logo queen, six moods. Generated by tools/generate_assets.py.',
           'static constexpr int QueenWidth = 42, QueenHeight = 62;',
           'static const uint16_t QueenTiles[6][QueenWidth * QueenHeight] = {']
    for i in range(6):
        im=Image.open(ROOT/f'assets/queen_moods/queen_{i}.webp').convert('RGBA')
        im=im.resize((42,62),Image.Resampling.LANCZOS)
        canvas=Image.new('RGBA',(42,62),(8,16,33,255));canvas.alpha_composite(im)
        data=[((r>>3)<<11)|((g>>2)<<5)|(b>>3) for r,g,b,a in canvas.getdata()]
        lines.append('{'+','.join(f'0x{x:04x}' for x in data)+'},')
    lines.append('};')
    return '\n'.join(lines)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Check without writing')
    args=parser.parse_args()
    for name,data in [('piece_tiles.h',pieces()),('queen_tiles.h',queens())]:
        path=MAIN/name
        if args.check:
            if path.read_text(encoding='utf8')!=data:
                raise SystemExit(f'{name}: differs; run this script without --check to regenerate')
            print(f'{name}: matches source images')
        else:
            path.write_text(data,encoding='utf8',newline='\n')
            print(f'{name}: written')

if __name__=='__main__':main()
